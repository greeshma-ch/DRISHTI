"""Telegram contact linking (P6) — secure start codes and chat_id capture."""

from __future__ import annotations

import hashlib
import hmac
import logging
import secrets
import time
from typing import Final

import httpx
from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel, Field

from .auth import verify_user_token
from .config import settings

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/telegram", tags=["telegram"])

# Code format: HMAC(user_id + nonce)[:16] + "." + nonce
# Expires in 15 minutes
CODE_TTL_SEC: Final = 900
CODE_PREFIX: Final = "tlg_"

# In-memory store for pending codes (code_without_prefix -> {user_id, expires_at, nonce})
# In production, use Redis or DB; for hackathon, in-memory is fine (single process)
_pending_codes: dict[str, dict] = {}

# In-memory store for captured chat_ids (code -> chat_id)
# This is what the polling endpoint returns
_captured_chats: dict[str, int] = {}

# Offset for getUpdates to avoid reprocessing
_getupdates_offset: int = 0


def _hmac_sign(data: str) -> str:
    """Compute HMAC-SHA256 of data using EMERGENCY_HMAC_SECRET."""
    return hmac.new(
        settings.EMERGENCY_HMAC_SECRET.encode("utf-8"),
        data.encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()


def generate_start_code(user_id: str) -> str:
    """
    Generate a start code for Telegram deep link.
    Code = HMAC(user_id + nonce)[:16] + "." + nonce
    Expires in 15 minutes.
    """
    nonce = secrets.token_urlsafe(16)
    data = f"{user_id}:{nonce}"
    sig = _hmac_sign(data)[:16]
    code = f"{sig}.{nonce}"
    expires_at = time.time() + CODE_TTL_SEC
    _pending_codes[code] = {
        "user_id": user_id,
        "expires_at": expires_at,
        "nonce": nonce,
    }
    return code


def verify_start_code(code: str) -> str | None:
    """
    Verify a start code and return user_id if valid and not expired.
    Removes the code from pending store on success (one-time use).
    """
    if code not in _pending_codes:
        return None
    entry = _pending_codes[code]
    if time.time() > entry["expires_at"]:
        del _pending_codes[code]
        return None
    # One-time use: remove on verification
    user_id = entry["user_id"]
    del _pending_codes[code]
    return user_id


class ConnectResponse(BaseModel):
    deep_link: str
    code: str
    expires_in: int


@router.get("/connect")
async def telegram_connect(
    user_id: str = Query(...),
    token: str = Query(...),
) -> ConnectResponse:
    """
    Generate a Telegram deep-link for a contact to connect.
    Returns: {deep_link, code, expires_in}
    Contact opens t.me/<bot>?start=<code>, presses Start.
    """
    if not verify_user_token(user_id, token):
        raise HTTPException(status_code=401, detail="Invalid token")

    if not settings.TELEGRAM_BOT_TOKEN:
        raise HTTPException(status_code=503, detail="Telegram bot not configured")

    # Extract bot username from token (format: 123456789:ABC-DEF...)
    # We can't reliably get username from token alone, so use a placeholder
    # In production, cache bot username from getMe
    bot_username = "drishti_bot"  # placeholder; update with actual bot username

    code = generate_start_code(user_id)
    deep_link = f"https://t.me/{bot_username}?start={CODE_PREFIX}{code}"

    return ConnectResponse(
        deep_link=deep_link,
        code=code,
        expires_in=CODE_TTL_SEC,
    )


class ManualChatIdRequest(BaseModel):
    code: str
    chat_id: int = Field(..., gt=0)


@router.post("/manual")
async def telegram_manual(
    body: ManualChatIdRequest,
    user_id: str = Query(...),
    token: str = Query(...),
) -> dict[str, str]:
    """
    Manual chat_id entry fallback.
    Sighted helper enters the chat_id directly if deep-link fails.
    """
    if not verify_user_token(user_id, token):
        raise HTTPException(status_code=401, detail="Invalid token")

    # Verify code belongs to this user
    stored_user_id = verify_start_code(body.code)
    if stored_user_id != user_id:
        raise HTTPException(status_code=400, detail="Invalid or expired code")

    _captured_chats[body.code] = body.chat_id
    logger.info("Manual chat_id captured for user=%s code=%s", user_id, body.code)
    return {"status": "ok"}


class PollResponse(BaseModel):
    chat_id: int | None = None
    connected: bool


@router.get("/poll")
async def telegram_poll(
    user_id: str = Query(...),
    token: str = Query(...),
) -> PollResponse:
    """
    Poll for captured chat_id.
    Only returns chat_id for a code generated by THIS user.
    Never returns other users' chat_ids or logs them.
    """
    if not verify_user_token(user_id, token):
        raise HTTPException(status_code=401, detail="Invalid token")

    # Check if any pending code for this user has been captured
    for code, entry in list(_pending_codes.items()):
        if entry["user_id"] == user_id:
            if code in _captured_chats:
                chat_id = _captured_chats.pop(code)
                # Also clean up the pending code
                del _pending_codes[code]
                return PollResponse(chat_id=chat_id, connected=True)

    return PollResponse(chat_id=None, connected=False)


async def poll_telegram_updates() -> None:
    """
    Background task: poll Telegram getUpdates and capture chat_ids for valid start codes.
    Only processes messages with text matching "/start <CODE_PREFIX><code>".
    Only stores chat_id for codes in _pending_codes.
    NEVER logs or returns other updates.
    """
    global _getupdates_offset

    if not settings.TELEGRAM_BOT_TOKEN:
        return

    url = f"{TELEGRAM_API_BASE}{settings.TELEGRAM_BOT_TOKEN}/getUpdates"
    params = {
        "offset": _getupdates_offset,
        "timeout": 5,  # long poll
        "allowed_updates": ["message"],
    }

    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            resp = await client.get(url, params=params)
            if resp.status_code != 200:
                logger.warning("Telegram getUpdates failed: %s", resp.status_code)
                return

            data = resp.json()
            if not data.get("ok"):
                logger.warning("Telegram getUpdates error: %s", data.get("description"))
                return

            updates = data.get("result", [])
            if not updates:
                return

            for update in updates:
                _getupdates_offset = update["update_id"] + 1
                message = update.get("message")
                if not message:
                    continue

                text = message.get("text", "")
                if not text.startswith("/start "):
                    continue

                start_payload = text[7:].strip()
                if not start_payload.startswith(CODE_PREFIX):
                    continue

                code = start_payload[len(CODE_PREFIX) :]
                # Verify this is a code we generated
                if code not in _pending_codes:
                    continue  # Silently ignore unknown codes

                chat = message.get("chat")
                if not chat:
                    continue

                chat_id = chat.get("id")
                if not chat_id:
                    continue

                # Store chat_id for this code (will be picked up by /poll)
                _captured_chats[code] = chat_id
                logger.info("Captured chat_id for code=%s", code)

    except Exception as exc:
        logger.warning("Telegram getUpdates poll error: %s", exc)


# For background task integration
TELEGRAM_API_BASE: Final = "https://api.telegram.org/bot"
